import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const root = join(import.meta.dirname, '../..')

function read(rel: string) {
  return readFileSync(join(root, rel), 'utf8')
}

describe('layer ownership', () => {
  it('gives website marketing `/` and the app the dashboard `/`', () => {
    expect(existsSync(join(root, 'app/website/app/pages/index.vue'))).toBe(true)
    expect(existsSync(join(root, 'app/layers/docs/app/pages/index.vue'))).toBe(false)
    expect(existsSync(join(root, 'app/ui/pages/index.vue'))).toBe(true)
    expect(read('app/website/app/pages/index.vue')).toContain('jasenmichael.github.io/bros/install.sh')
    expect(read('app/website/app/pages/index.vue')).not.toContain('Dashboard')
    expect(read('app/ui/pages/index.vue')).toContain('Dashboard')
    expect(read('app/ui/pages/index.vue')).not.toContain('jasenmichael.github.io/bros/install.sh')
  })

  it('keeps `/docs` only in the docs layer', () => {
    expect(existsSync(join(root, 'app/layers/docs/app/pages/docs/index.vue'))).toBe(true)
    expect(existsSync(join(root, 'app/layers/docs/app/pages/docs/[...slug].vue'))).toBe(true)
    expect(existsSync(join(root, 'app/ui/pages/docs'))).toBe(false)
    expect(existsSync(join(root, 'app/website/app/pages/docs'))).toBe(false)
    expect(read('app/layers/docs/app/pages/docs/index.vue')).toContain('Documentation')
  })

  it('puts the shared shell in theme, not in either app', () => {
    expect(existsSync(join(root, 'app/layers/theme/app/app.vue'))).toBe(true)
    expect(existsSync(join(root, 'app/ui/app.vue'))).toBe(false)
    expect(existsSync(join(root, 'app/layers/docs/app/app.vue'))).toBe(false)
    expect(read('app/layers/theme/app/app.vue')).toContain('NuxtLayout')
    expect(read('app/layers/theme/app/layouts/default.vue')).toContain('BrosAppNav')
    expect(read('app/ui/app.config.ts')).toContain('Dashboard')
    expect(read('app/ui/app.config.ts')).toContain("to: '/desktop'")
    expect(read('app/ui/app.config.ts')).toContain("to: '/agents'")
    expect(read('app/ui/app.config.ts')).toContain("to: '/status'")
    expect(read('app/ui/app.config.ts')).not.toContain("to: '/apps'")
    expect(read('app/ui/app.config.ts')).not.toContain("label: 'Providers'")
    expect(read('app/ui/app.config.ts')).not.toContain("label: 'Models'")
    expect(read('app/ui/app.config.ts')).not.toContain("to: '/models'")
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).toContain("to: '/chat'")
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).not.toContain("to: '/providers'")
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).not.toContain("to: '/agents'")
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).toContain('BrosChatRecents')
    expect(read('app/ui/app.config.ts')).toContain('docsNavItems')
    expect(read('app/website/app/app.config.ts')).toContain('docsNavItems')
    expect(read('app/layers/docs/app/utils/docsNav.ts')).toContain('Getting started')
    expect(read('app/layers/docs/app/utils/docsNav.ts')).toContain("to: '/docs/providers'")
    expect(read('app/layers/docs/app/utils/docsNav.ts')).toContain("to: '/docs/providers/custom'")
    expect(read('app/layers/docs/app/utils/docsNav.ts')).toContain("to: '/docs/development'")
    expect(read('app/layers/theme/app/components/BrosAppNav.vue')).toContain('BrosNavTree')
    expect(read('app/layers/docs/app/pages/docs/[...slug].vue')).toContain('BrosDocsCrumbs')
  })

  it('hides recents scrollbar in theme dock chrome', () => {
    const nav = read('app/layers/theme/app/components/BrosAppNav.vue')
    const recents = read('app/ui/components/BrosChatRecents.vue')
    const themeCss = read('app/layers/theme/app/assets/css/main.css')
    expect(themeCss).toContain('scrollbar-width: thin')
    expect(themeCss).toContain('::-webkit-scrollbar')
    expect(themeCss).toContain('::-webkit-scrollbar-thumb')
    expect(nav).toContain('bros-nav-panel__section--chat')
    expect(nav).toContain('bros-nav-panel__section--primary')
    expect(nav).toContain('bros-nav-panel__section--footer')
    expect(nav).toContain('min-height: min-content')
    expect(nav).toContain('bros-nav-panel__scroll')
    expect(nav).toContain('bros-nav-panel__divider--drag')
    expect(nav).toContain('aria-label="Footer"')
    expect(nav).toContain('flex-shrink: 0')
    expect(nav).toContain('scrollbar-width: none')
    expect(nav).toContain('github.com/jasenmichael/bros')
    expect(nav).not.toContain('bros-nav-panel__footer')
    expect(nav).not.toContain('border-top: 1px solid #2a3544')
    expect(nav).not.toContain('bros-nav-panel__recents-hint--up')
    expect(recents).toContain('scrollbar-width: none')
    expect(recents).toContain('::-webkit-scrollbar')
    expect(recents).toContain('i-lucide-chevron-up')
    expect(recents).toContain('i-lucide-chevron-down')
    expect(recents).toContain('overflow-y: auto')
    expect(recents).toContain('recentsOpen = ref(false)')
    expect(recents).not.toContain('aria-label="Previous chats"')
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).toContain('BrosNavTree')
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).toContain('BrosChatRecents')
    expect(read('app/ui/components/BrosNavAfterPrimary.vue')).not.toContain('bros-nav-panel__divider')
    expect(recents.indexOf('bros-recents__toggle')).toBeLessThan(recents.indexOf('bros-nav-panel__recents-hint--up'))
    expect(recents.indexOf('bros-nav-panel__recents-hint--up')).toBeLessThan(recents.indexOf('bros-recents__list'))
    expect(recents.indexOf('bros-recents__list')).toBeLessThan(recents.indexOf('bros-nav-panel__recents-hint--down'))
    expect(read('app/layers/theme/app/app.config.ts')).toContain('showAfterPrimary: false')
    expect(read('app/ui/app.config.ts')).toContain('showAfterPrimary: true')
  })

  it('truncates dock labels on one line instead of wrapping', () => {
    const tree = read('app/layers/theme/app/components/BrosNavTree.vue')
    const nav = read('app/layers/theme/app/components/BrosAppNav.vue')
    const recents = read('app/ui/components/BrosChatRecents.vue')
    for (const src of [tree, nav, recents]) {
      expect(src).toContain('bros-nav-label')
      expect(src).toContain('white-space: nowrap')
      expect(src).toContain('text-overflow: ellipsis')
    }
  })

  it('has both apps extend docs then theme', () => {
    const app = read('app/ui/nuxt.config.ts')
    const website = read('app/website/nuxt.config.ts')
    const docs = read('app/layers/docs/nuxt.config.ts')
    expect(app).toContain("'../layers/docs'")
    expect(app).toContain("'../layers/theme'")
    expect(website).toContain("'../layers/docs'")
    expect(website).toContain("'../layers/theme'")
    expect(docs).not.toContain('@bros/theme')
    expect(docs).toContain("'../theme'")
    expect(website).toContain('/docs/install')
    expect(website).toContain('/docs/providers/openai')
    expect(website).toContain('/docs/apps/ollama')
    expect(website).toContain('/docs/development')
  })
})
